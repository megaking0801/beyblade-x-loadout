/** 依詞素表把日文名稱轉成繁體中文暫譯。回傳未命中的殘留片段供稽核。 */
export function translate(nameJa) {
  const sorted = [...TOKENS].sort((a, b) => b[0].length - a[0].length)
  let rest = nameJa
  const pieces = []
  let guard = 0
  while (rest.length > 0 && guard < 500) {
    guard += 1
    const hit = sorted.find(([ja]) => rest.startsWith(ja))
    if (hit) {
      pieces.push({ type: 'zh', text: hit[1] })
      rest = rest.slice(hit[0].length)
      continue
    }
    const char = rest[0]
    pieces.push({ type: 'raw', text: char })
    rest = rest.slice(1)
  }
  const translated = pieces.map((p) => p.text).join('')
  const untranslated = pieces
    .filter((p) => p.type === 'raw' && /[぀-ヿ一-鿿]/.test(p.text))
    .map((p) => p.text)
    .join('')
  return { translated, untranslated }
}
